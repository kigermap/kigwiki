URL = re.compile(r'https?://[^\s<>\[\]"「」【】（），。]+')


def load_collection():
    return json.loads(DATA.read_text())


def rich_text(text):
    parts = []
    last = 0
    for match in URL.finditer(text):
        parts.append(escape(text[last:match.start()]))
        url = match.group()
        if urlsplit(url).scheme not in {'https', 'http'} or not urlsplit(url).netloc:
            raise ValueError('Invalid source URL')
        parts.append(f'<a href="{escape(url, quote=True)}" rel="noopener noreferrer">{escape(url)}</a>')
        last = match.end()
    parts.append(escape(text[last:]))
    return ''.join(parts).replace('\n', '<br>')


def image_html(key, caption):
    # All paths are content-independent local identifiers, never remote signed URLs.
    assert re.fullmatch('[a-f0-9]{16}', key)
    path = f'/assets/images/feishu-shops-2026-11-03/{key}.webp'
    return f'<figure><a href="{path}" target="_blank" rel="noopener"><img src="{path}" alt="{escape(caption, quote=True)}" loading="lazy" decoding="async"></a><figcaption>{escape(caption)}</figcaption></figure>'


def entry_images(entry):
    images = [{'src': f'/assets/images/feishu-shops-2026-11-03/{key}.webp', 'caption': f'{entry["name"]} · 原文配图 {n}', 'credit': entry['source_url']} for n,key in enumerate(entry['images'],1)]
    # The source usually places a small shop avatar before the full-size work photos.
    # Keep every image, while promoting a full-size image for the cover and gallery.
    if len(images) > 1:
        sizes = image_sizes()
        first = sizes[entry['images'][0]]
        second = sizes[entry['images'][1]]
        if first[0] * first[1] * 1.5 < second[0] * second[1]:
            images = images[1:] + images[:1]
    return images


@lru_cache(maxsize=1)
def image_sizes():
    manifest = json.loads((IMAGE_DIR/'manifest.json').read_text())
    return {Path(item['path']).stem: item['original_size'] for item in manifest['images']}


def entry_html(entry, heading=True, show_images=True):
    lines=['<div class="collection-entry">']
    if heading: lines.append(f'<h3>{escape(entry["name"])} <span class="maker-caption">{LABELS[entry["category"]]}</span></h3>')
    if entry['source_incomplete']: lines.append('<p class="maker-caption">原文带 # 标记，部分资料尚待补充。</p>')
    primary=['参考价格','定金','工期时间']
    filled=[(label,entry['fields'].get(label)) for label in primary if entry['fields'].get(label)]
    if filled:
        lines.append('<dl class="collection-facts">'+''.join(fact(label,value) for label,value in filled)+'</dl>')
    lines.append('<dl class="collection-fields">')
    for label,value in entry['fields'].items():
        if label in primary or not value: continue
        html=rich_text(value)
        if '链接' in label or '视频' in label:
            html=re.sub(r'(<a href="[^"]+"[^>]*>)(https?://[^<]+)(</a>)',lambda m:m[1]+escape(urlsplit(m[2]).netloc.removeprefix('www.'))+' ↗'+m[3],html)
        lines.append(f'<div><dt>{escape(label)}</dt><dd>{html}</dd></div>')
    lines.append('</dl>')
    missing=[label for label,value in entry['fields'].items() if not value]
    if missing: lines.append('<p class="maker-caption">原文未填写：'+escape('、'.join(missing))+'。</p>')
    if show_images and entry['images']:
        lines.append('<div class="collection-gallery">')
        for n,key in enumerate(entry['images'],1): lines.append(image_html(key,f'{entry["name"]} · 原文配图 {n}'))
        lines.append('</div>')
    lines.append(f'<p class="collection-source-note">图文来源：禾芷溪溪溪溪溪溪 · 《Kigurumi 店铺合集 Ver2.0》 · 2026-11-03 采集 · <a href="{escape(entry["source_url"],quote=True)}">原文对应位置 ↗</a>。图片权利归原权利人。</p></div>')
    return '\n'.join(lines)


