ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'docs/assets/data/feishu-shop-collection.json'
IMAGE_DIR = ROOT / 'docs/assets/images/feishu-shops-2026-11-03'
DEST = ROOT / 'docs/zh-Hans/makers/collection'
ARCHIVE = ROOT / 'docs/zh-Hans/sources/shop-collections/hezhi-2026/index.md'
LABELS = {'anime': '二次元头壳', 'bjd': 'BJD 风格头壳', 'hadatai': '肤色衣'}
URL = re.compile(r'https?://[^\s<>\[\]"「」【】（），。]+')


def load_collection():
    return json.loads(DATA.read_text())


def rich_text(text):
    parts = []
    last = 0
    for match in URL.finditer(text):
        parts.append(escape(text[last:match.start()]))
        url = match.group()
        if urlsplit(url).scheme not in {'https', 'http'} or not urlsplit(url).netloc:
            raise ValueError('Invalid source URL')
        parts.append(f'<a href="{escape(url, quote=True)}" rel="noopener noreferrer">{escape(url)}</a>')
        last = match.end()
    parts.append(escape(text[last:]))
    return ''.join(parts).replace('\n', '<br>')


def image_html(key, caption):
    # All paths are content-independent local identifiers, never remote signed URLs.
    assert re.fullmatch('[a-f0-9]{16}', key)
    path = f'/assets/images/feishu-shops-2026-11-03/{key}.webp'
    return f'<figure><a href="{path}" target="_blank" rel="noopener"><img src="{path}" alt="{escape(caption, quote=True)}" loading="lazy" decoding="async"></a><figcaption>{escape(caption)}</figcaption></figure>'


def entry_html(entry, heading=True):
    lines = []
    if heading:
        lines.append(f'<h3>{escape(entry["name"])} · {LABELS[entry["category"]]}</h3>')
    if entry['source_incomplete']:
        lines.append('<p class="collection-source-note">原文带 # 标记：编者尚未查明全部信息。</p>')
    lines.append('<div class="maker-table-scroll"><table class="maker-table"><thead><tr><th>原文项目</th><th>合集记载</th></tr></thead><tbody>')
    for label, value in entry['fields'].items():
        lines.append(f'<tr><th scope="row">{escape(label)}</th><td>{rich_text(value) if value else "原文未填写"}</td></tr>')
    lines.append('</tbody></table></div>')
    if entry['images']:
        lines.append('<div class="collection-gallery">')
        for n, key in enumerate(entry['images'], 1):
            lines.append(image_html(key, f'{entry["name"]} · 原文配图 {n}'))
        lines.append('</div>')
    lines.append(f'<p class="collection-source-note">图文来源：禾芷溪溪溪溪溪溪《Kigurumi 店铺合集文档 Ver2.0（测试版）》 · 采集于 2026-11-03 · <a href="{escape(entry["source_url"], quote=True)}">查看原文对应位置</a>。图片权利归原权利人。</p>')
    return '\n'.join(lines)


def front(title, description, hide=False):
    return '\n'.join(['---', 'title: '+json.dumps(title,ensure_ascii=False), 'description: '+json.dumps(description,ensure_ascii=False), *(['hide:', '  - toc'] if hide else []), '---', '', '<!-- Generated by scripts/build_shop_collection.py. -->', ''])


