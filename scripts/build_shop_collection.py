def validate(data):
    assert data['counts']==dict(Counter(e['category'] for e in data['entries']))
    ids=[e['id'] for e in data['entries']];assert len(ids)==len(set(ids))
    all_images=[b['image'] for s in data['sections'] for b in s['blocks'] if b['type']=='image']
    assert len(all_images)==data['image_occurrences']==379
    assert all('傻鸟' not in e['name'] and e['name']!='模块' for e in data['entries'])
    manifest=json.loads((IMAGE_DIR/'manifest.json').read_text())
    failures=[x for x in manifest['images'] if x['status']!='downloaded']
    assert not failures, f'{len(failures)} source images still unavailable'
    for key in all_images:assert (IMAGE_DIR/f'{key}.webp').is_file(),key
    assert len(manifest['images'])==len(set(all_images))
    manifest_keys = {hashlib.sha256(item['token'].encode()).hexdigest()[:16] for item in manifest['images']}
    assert manifest_keys == set(all_images), 'Image manifest differs from source blocks'
    for item in [*manifest['images'], data['cover']]:
        path = ROOT/'docs'/item['path']
        assert path.is_file(), str(path)
        assert hashlib.sha256(path.read_bytes()).hexdigest() == item['web_sha256'], str(path)


def render(check=False):
    data=load_collection();validate(data)
    files={DEST/'index.md':index(data),ARCHIVE:archive(data)}
    files.update({DEST/e['id']/'index.md':detail(data,e) for e in data['entries']})
    # A complete portable text copy has public image references instead of temporary download codes.
    portable=files[ARCHIVE].replace('src="/','src="https://kigwiki.com/').replace('href="/','href="https://kigwiki.com/')
    def portable_link(match):
        target = match[2]
        if not urlsplit(target).scheme:
            target = urljoin('https://kigwiki.com/sources/shop-collections/hezhi-2026/', target)
            target = target.removesuffix('index.md')
        return f'[{match[1]}]({target})'
    portable = re.sub(r'\[([^\]]+)\]\(([^)]+)\)', portable_link, portable)
    files[ROOT/'docs/assets/data/feishu-shop-collection.md']=portable
    outdated=[]
    for p,value in files.items():
        value=value.rstrip()+'\n'
        if check:
            if not p.exists() or p.read_text()!=value:outdated.append(str(p.relative_to(ROOT)))
        else:p.parent.mkdir(parents=True,exist_ok=True);p.write_text(value)
    if outdated:raise SystemExit('Regenerate collection: '+', '.join(outdated))
    print(f'{"Checked" if check else "Rendered"} {len(data["entries"])} source entries, complete archive and {data["image_occurrences"]} local images.')

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');render(parser.parse_args().check)
